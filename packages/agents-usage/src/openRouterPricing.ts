function listRate(
  model: string,
  input: number,
  output: number,
  cacheRead: number,
  cacheWrite: number,
  cacheWrite1h: number,
  long?: readonly [number, number, number, number, number, number],
): OpenRouterListRate {
  return {
    model,
    input,
    output,
    cacheRead,
    cacheWrite,
    cacheWrite1h,
    ...(long
      ? {
          longContext: {
            thresholdTokens: long[0],
            input: long[1],
            output: long[2],
            cacheRead: long[3],
            cacheWrite: long[4],
            cacheWrite1h: long[5],
          },
        }
      : {}),
  };
}

const BY_KEY = new Map<string, OpenRouterListRate>();
for (const row of RATES) {
  const rate =
    row.length === 7
      ? listRate(row[0], row[1], row[2], row[3], row[4], row[5], row[6])
      : listRate(row[0], row[1], row[2], row[3], row[4], row[5]);
  BY_KEY.set(rate.model, rate);
  const slash = rate.model.lastIndexOf("/");
  const bare = slash === -1 ? rate.model : rate.model.slice(slash + 1);
  if (!BY_KEY.has(bare)) BY_KEY.set(bare, rate);
}

/** First catalog route whose id matches a candidate and is already effective. */
export function openRouterListRate(
  candidates: readonly string[],
  day: string,
): OpenRouterListRate | undefined {
  if (day < OPENROUTER_REVIEWED) return undefined;
  for (const candidate of candidates) {
    const rate = BY_KEY.get(candidate);
    if (rate) return rate;
  }
  return undefined;
}
