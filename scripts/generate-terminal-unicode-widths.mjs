import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Unicode11Addon } from "@xterm/addon-unicode11";

const root = new URL("../", import.meta.url);
let provider;
new Unicode11Addon().activate({
  unicode: {
    register: (value) => {
      provider = value;
    },
  },
});
if (provider?.version !== "11") throw new Error("Expected the renderer's Unicode 11 provider");

const ranges = { 0: [], 2: [] };
for (let point = 0; point <= 0x10ffff; point += 1) {
  const width = provider.wcwidth(point);
  if (width === 1) continue;
  const entries = ranges[width];
  if (!entries) throw new Error("Unsupported terminal column width");
  const last = entries.at(-1);
  if (last && last[1] + 1 === point) last[1] = point;
  else entries.push([point, point]);
}

const license = readFileSync(new URL("node_modules/@xterm/addon-unicode11/LICENSE", root), "utf8");
const header = [
  "// Generated by scripts/generate-terminal-unicode-widths.mjs. Do not edit.",
  "// Widths match the renderer's @xterm/addon-unicode11 provider (version 11).",
  ...license
    .trim()
    .split("\n")
    .map((line) => (line ? "// " + line : "//")),
  "",
].join("\n");
const hex = (value) => "0x" + value.toString(16).toUpperCase();
const swiftRanges = (width) =>
  ranges[width].map(([low, high]) => "    " + hex(low) + "..." + hex(high) + ",").join("\n");
const kotlinRanges = (width) =>
  ranges[width].map(([low, high]) => "        " + hex(low) + ", " + hex(high) + ",").join("\n");

const swift =
  header +
  [
    "enum TerminalUnicodeWidth {",
    "  static func columns(for scalar: Unicode.Scalar) -> Int {",
    "    if contains(scalar.value, in: zeroWidth) { return 0 }",
    "    return contains(scalar.value, in: doubleWidth) ? 2 : 1",
    "  }",
    "",
    "  private static func contains(_ value: UInt32, in ranges: [ClosedRange<UInt32>]) -> Bool {",
    "    var low = 0",
    "    var high = ranges.count",
    "    while low < high {",
    "      let mid = low + (high - low) / 2",
    "      if value < ranges[mid].lowerBound { high = mid }",
    "      else if value > ranges[mid].upperBound { low = mid + 1 }",
    "      else { return true }",
    "    }",
    "    return false",
    "  }",
    "",
    "  private static let zeroWidth: [ClosedRange<UInt32>] = [",
    swiftRanges(0),
    "  ]",
    "  private static let doubleWidth: [ClosedRange<UInt32>] = [",
    swiftRanges(2),
    "  ]",
    "}",
    "",
  ].join("\n");
const kotlin =
  "package com.poracode.app.ui.terminal\n\n" +
  header +
  [
    "internal object TerminalUnicodeWidth {",
    "    fun columns(codePoint: Int): Int = when {",
    "        contains(codePoint, zeroWidth) -> 0",
    "        contains(codePoint, doubleWidth) -> 2",
    "        else -> 1",
    "    }",
    "",
    "    private fun contains(value: Int, ranges: IntArray): Boolean {",
    "        var low = 0",
    "        var high = ranges.size / 2",
    "        while (low < high) {",
    "            val mid = low + (high - low) / 2",
    "            if (value < ranges[mid * 2]) high = mid",
    "            else if (value > ranges[mid * 2 + 1]) low = mid + 1",
    "            else return true",
    "        }",
    "        return false",
    "    }",
    "",
    "    private val zeroWidth = intArrayOf(",
    kotlinRanges(0),
    "    )",
    "    private val doubleWidth = intArrayOf(",
    kotlinRanges(2),
    "    )",
    "}",
    "",
  ].join("\n");

for (const [relativePath, content] of [
  ["ios/App/App/Features/Terminal/TerminalUnicodeWidth.swift", swift],
  ["android/app/src/main/kotlin/com/poracode/app/ui/terminal/TerminalUnicodeWidth.kt", kotlin],
  ["ios/App/App/Resources/TerminalUnicodeLicense.txt", license],
  ["android/app/src/main/res/raw/terminal_unicode_license.txt", license],
]) {
  const path = fileURLToPath(new URL(relativePath, root));
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content)
      throw new Error("Generated width drift: " + relativePath);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
