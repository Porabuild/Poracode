import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const output = await Bun.build({
  entrypoints: [resolve(root, "src/shared/mcpApps/nativeHost.ts")],
  target: "browser",
  format: "iife",
  minify: true,
});
if (!output.success) throw new Error(output.logs.map((log) => log.message).join("\n"));
const script = `// Generated by bun run mcp-apps:native:generate; do not edit.\n${await output.outputs[0].text()}\n`;
for (const relative of [
  "ios/App/App/Resources/mcp-app-host.js",
  "android/app/src/main/assets/mcp-app-host.js",
]) {
  const path = resolve(root, relative);
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== script)
      throw new Error(`Stale MCP App host: ${relative}`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, script);
  }
}
